/**
 * Stage Task Dependencies for VSIX Packaging
 *
 * Installs production dependencies into each Azure DevOps task folder.
 * The tfx packaging tool requires a flat node_modules layout with no
 * symlinks. pnpm always creates symlinks (even with --shamefully-hoist),
 * so task staging uses npm to produce a tfx-compatible layout.
 *
 * This is the ONE exception to the repo's pnpm-only policy — tfx
 * cannot read pnpm's symlinked node_modules. The npm install runs
 * transiently during packaging only; no package-lock.json is committed.
 * --legacy-peer-deps avoids resolution crashes on npm 11.x (Node 24).
 *
 * The script cleans any existing node_modules before installing to
 * ensure a consistent layout regardless of prior state.
 *
 * Usage: node scripts/stage-task-deps.mjs
 * Called by: pnpm run package:vsix
 */

import { execSync } from 'child_process';
import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const tasksDir = path.resolve(__dirname, '../tasks');

// Tasks to skip (not actual pipeline tasks)
const SKIP_DIRS = ['_shared'];

async function stageTaskDeps() {
    console.log('📦 Staging task dependencies for VSIX packaging...\n');

    const taskDirs = fs.readdirSync(tasksDir).filter((dir) => {
        const fullPath = path.join(tasksDir, dir);
        return (
            fs.statSync(fullPath).isDirectory() &&
            !SKIP_DIRS.includes(dir) &&
            fs.existsSync(path.join(fullPath, 'package.json'))
        );
    });

    if (taskDirs.length === 0) {
        console.log('⚠ No task directories with package.json found');
        return;
    }

    for (const taskDir of taskDirs) {
        const taskPath = path.join(tasksDir, taskDir);
        const nodeModulesPath = path.join(taskPath, 'node_modules');

        console.log(`📁 ${taskDir}/`);

        // Clean existing node_modules to ensure consistent layout.
        // Mixed pnpm/npm state causes tfx EISDIR errors.
        if (fs.existsSync(nodeModulesPath)) {
            console.log('   Cleaning stale node_modules...');
            fs.rmSync(nodeModulesPath, { recursive: true, force: true });
        }

        // Use npm (not pnpm) to produce a flat node_modules that tfx can
        // read. pnpm always creates symlinks — even with --shamefully-hoist
        // — which cause tfx EISDIR errors. This is the one exception to
        // the repo's pnpm-only policy; no package-lock.json is committed.
        // --legacy-peer-deps avoids resolution crashes on npm 11.x.
        const installCmd = 'npm install --production --legacy-peer-deps';
        console.log(`   Running: ${installCmd}`);

        try {
            execSync(installCmd, {
                cwd: taskPath,
                stdio: ['pipe', 'pipe', 'pipe'],
                encoding: 'utf-8',
            });

            // Verify critical dependency installed
            const taskLibPath = path.join(
                nodeModulesPath,
                'azure-pipelines-task-lib'
            );

            // Clean transient package-lock.json generated by npm install.
            // The repo's pnpm guard rejects committed package-lock.json.
            const transientLock = path.join(taskPath, 'package-lock.json');
            if (fs.existsSync(transientLock)) {
                fs.unlinkSync(transientLock);
            }

            if (fs.existsSync(taskLibPath)) {
                const depCount = fs.readdirSync(nodeModulesPath).filter(
                    (entry) => !entry.startsWith('.')
                ).length;
                console.log(`   ✓ Staged ${depCount} packages\n`);
            } else {
                console.error(
                    `   ✗ CRITICAL: azure-pipelines-task-lib not found!`
                );
                process.exit(1);
            }
        } catch (err) {
            console.error(`   ✗ Failed to install dependencies: ${err.message}`);
            process.exit(1);
        }
    }

    console.log('✅ All task dependencies staged successfully!');
    console.log('   Run: tfx extension create --manifest-globs vss-extension.json');
}

stageTaskDeps().catch((err) => {
    console.error('Staging failed:', err);
    process.exit(1);
});
